// Generates the app icon and the two theme-aware tray icons from the chosen
// direction's SVG masters.
//
//   node generate-icon.js
//
// ── Why this file is now an SVG rasteriser ────────────────────────────────
// It used to draw the icon pixel-by-pixel in JavaScript: a blue disc with three
// white orbital rings, hand-computed in a double loop. That artwork is replaced by
// the chosen direction (CAPTURE — the selection frame with the mark inside it),
// whose drawing needs a superellipse, four gradient layers, a drop shadow and an
// even-odd ring. None of that is worth re-implementing as per-pixel maths: the
// vector source is the single source of truth, and this script only rasterises it
// at the sizes Windows asks for.
//
// The SVG masters live in design-demos/app-icon/assets/ and are generated by
// design-demos/app-icon/tools/capture-source.mjs. They are committed, so a plain
// `node generate-icon.js` works without the design tooling.
//
// ── What each output is for ───────────────────────────────────────────────
//   assets/icon.ico         packaged app icon (electron-builder: package.json
//                           "icon" + "installerIcon"), Explorer, taskbar
//   assets/icon.png         OPAQUE-source app artwork; also the tray icon on a
//                           light taskbar (main/services/tray-icon.js)
//   assets/icon-dark.png    tray icon on a DARK taskbar. Windows does not recolour
//                           tray bitmaps, and this icon's tile is graphite — on a
//                           #202020 taskbar the tile's own edge is 1.06:1, so the
//                           tile dissolves. The dark variant inverts the material
//                           (warm light tile, graphite frame, amber mark) while
//                           keeping the same drawing.
//
// ── The two rendering regimes ─────────────────────────────────────────────
// 24px and below use separate art (thicker frame, no gradient, no drop shadow),
// because at that size a gradient and a shadow are smear, not craft. The tray is
// always 24px logical, so its files use the small regime; the app icon is rendered
// at every ICO size from the large master, except that the shell will pick the
// dedicated 16/20/24 frames out of the .ico.

'use strict'

const fs = require('fs')
const path = require('path')
const zlib = require('zlib')

const ROOT = __dirname
const ASSETS = path.join(ROOT, 'assets')
const SOURCE = path.join(ROOT, 'design-demos', 'app-icon', 'assets')

// 20/40 are the 125%/150% DPI steps Windows asks for; 44 is the Start-menu tile;
// 96 is 400% DPI. The previous ico carried only 7 sizes and let the shell resample
// the rest, which is visible as soft edges in Explorer's large-icon views.
const ICO_SIZES = [16, 20, 24, 32, 40, 44, 48, 64, 96, 128, 256]
const TRAY_SIZES = [24]
// The tray source is 4x the logical size so a 125-200% display downsamples rather
// than upscales a 24px bitmap when tray-icon.js calls resize({width:24}).
const TRAY_SOURCE = 256

// ── minimal PNG reader/writer ──────────────────────────────────────────────
// No image dependency: the artwork is rasterised by the design tooling (Chromium)
// into plain RGBA PNGs, and all this file has to do is read those, and re-encode
// them inside the ICO container. PNG in / PNG out keeps the ICO lossless.

function readPng(file) {
  const buf = fs.readFileSync(file)
  if (buf.length < 24 || buf.readUInt32BE(0) !== 0x89504e47) {
    throw new Error(`${file}: not a PNG`)
  }
  const width = buf.readUInt32BE(16)
  const height = buf.readUInt32BE(20)
  const bitDepth = buf[24]
  const colorType = buf[25]
  if (bitDepth !== 8 || colorType !== 6) {
    // colorType 6 = truecolour + alpha, which is what the rasteriser emits
    throw new Error(`${file}: expected 8-bit RGBA (got depth ${bitDepth}, type ${colorType})`)
  }
  // Walk the chunk list to IDAT so the raw RGBA can be decoded.
  let off = 8
  const idat = []
  while (off < buf.length) {
    const len = buf.readUInt32BE(off)
    const type = buf.toString('ascii', off + 4, off + 8)
    if (type === 'IDAT') idat.push(buf.subarray(off + 8, off + 8 + len))
    if (type === 'IEND') break
    off += 12 + len
  }
  const raw = zlib.inflateSync(Buffer.concat(idat))
  const stride = width * 4
  const out = Buffer.alloc(height * stride)
  // Undo the per-scanline filters (only 0/1/2/3/4 are valid; 0 is what we emit,
  // but decode all of them so the reader cannot silently corrupt a file).
  let prev = Buffer.alloc(stride)
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)]
    const line = raw.subarray(y * (stride + 1) + 1, y * (stride + 1) + 1 + stride)
    const cur = Buffer.alloc(stride)
    for (let i = 0; i < stride; i++) {
      const a = i >= 4 ? cur[i - 4] : 0
      const b = prev[i]
      const c = i >= 4 ? prev[i - 4] : 0
      let v = line[i]
      if (filter === 1) v = (v + a) & 0xff
      else if (filter === 2) v = (v + b) & 0xff
      else if (filter === 3) v = (v + ((a + b) >> 1)) & 0xff
      else if (filter === 4) {
        const p = a + b - c
        const pa = Math.abs(p - a)
        const pb = Math.abs(p - b)
        const pc = Math.abs(p - c)
        const pr = pa <= pb && pa <= pc ? a : (pb <= pc ? b : c)
        v = (v + pr) & 0xff
      }
      cur[i] = v
    }
    cur.copy(out, y * stride)
    prev = cur
  }
  return { width, height, rgba: out }
}

function crc32(buf) {
  let c = 0xffffffff
  for (let i = 0; i < buf.length; i++) {
    c ^= buf[i]
    for (let j = 0; j < 8; j++) c = (c >>> 1) ^ (c & 1 ? 0xedb88320 : 0)
  }
  return (c ^ 0xffffffff) >>> 0
}

function writePng(width, height, rgba, file) {
  const stride = width * 4
  const raw = Buffer.alloc(height * (stride + 1))
  for (let y = 0; y < height; y++) {
    raw[y * (stride + 1)] = 0
    rgba.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride)
  }
  const comp = zlib.deflateSync(raw, { level: 9 })
  const chunk = (type, data) => {
    const len = Buffer.alloc(4)
    len.writeUInt32BE(data.length, 0)
    const td = Buffer.concat([Buffer.from(type, 'ascii'), data])
    const crc = Buffer.alloc(4)
    crc.writeUInt32BE(crc32(td), 0)
    return Buffer.concat([len, td, crc])
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(width, 0)
  ihdr.writeUInt32BE(height, 4)
  ihdr[8] = 8   // bit depth
  ihdr[9] = 6   // truecolour + alpha
  fs.writeFileSync(file, Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', ihdr), chunk('IDAT', comp), chunk('IEND', Buffer.alloc(0))
  ]))
}

// ── ICO writer ─────────────────────────────────────────────────────────────
// Each directory entry stores the embedded PNG verbatim (Vista+ supports PNG
// frames). Writing 32-bit DIB frames instead would bloat the file and lose the
// alpha-precise edges the rasteriser produced.
function writeIco(frames, file) {
  const sorted = [...frames].sort((a, b) => b.width - a.width)
  const header = Buffer.alloc(6)
  header.writeUInt16LE(0, 0)          // reserved
  header.writeUInt16LE(1, 2)          // 1 = icon
  header.writeUInt16LE(sorted.length, 4)

  const entries = []
  let offset = 6 + sorted.length * 16
  for (const frame of sorted) {
    const entry = Buffer.alloc(16)
    entry[0] = frame.width >= 256 ? 0 : frame.width    // 0 means 256
    entry[1] = frame.height >= 256 ? 0 : frame.height
    entry[2] = 0                                        // palette size
    entry[3] = 0                                        // reserved
    entry.writeUInt16LE(1, 4)                           // colour planes
    entry.writeUInt16LE(32, 6)                          // bits per pixel
    entry.writeUInt32LE(frame.png.length, 8)
    entry.writeUInt32LE(offset, 12)
    entries.push(entry)
    offset += frame.png.length
  }

  fs.writeFileSync(file, Buffer.concat([header, ...entries, ...sorted.map((f) => f.png)]))
  return sorted.map((f) => f.width)
}

// ── main ───────────────────────────────────────────────────────────────────
function main() {
  // The committed source of truth is the SVG masters plus the rasterised frames
  // under .tmp/build (regenerated by the design tooling, and gitignored because
  // they are reproducible from the SVGs). This generator refuses to run on a stale
  // or partial set rather than emitting a half-drawn icon.
  const appDir = path.join(ROOT, 'design-demos', 'app-icon', '.tmp', 'build')
  const masters = ['capture-app.svg', 'capture-tray-light.svg', 'capture-tray-dark.svg']
  const missing = masters.filter((f) => !fs.existsSync(path.join(SOURCE, f)))
  if (missing.length) {
    throw new Error(
      `Missing icon masters in ${path.relative(ROOT, SOURCE)}: ${missing.join(', ')}\n` +
      'Re-run: node design-demos/app-icon/tools/capture-source.mjs'
    )
  }

  const frames = []
  for (const size of ICO_SIZES) {
    const file = path.join(appDir, `app-${size}.png`)
    if (!fs.existsSync(file)) {
      throw new Error(
        `Missing rasterised app frame ${size}px in ${path.relative(ROOT, appDir)}\n` +
        'Re-run: node design-demos/app-icon/tools/rasterize-capture.mjs'
      )
    }
    frames.push({ width: size, height: size, png: fs.readFileSync(file) })
  }
  const sizes = writeIco(frames, path.join(ASSETS, 'icon.ico'))
  console.log(`Icon generated: assets/icon.ico (${sizes.length} sizes: ${sizes.join(', ')})`)

  // Both tray PNGs come from the SMALL-regime art at TRAY_SOURCE (96px), not from
  // the 256px app master. Two reasons, and the second is the one that matters:
  //   1. tray-icon.js resizes the source down to 24px logical. Feeding it a 256px
  //      large-regime drawing means the gradient, drop shadow and 2.8px rim get
  //      averaged into mush at 24px — the tray is the one place these are
  //      guaranteed to be seen tiny.
  //   2. the light-regime file is what the tray shows on a LIGHT taskbar; the dark
  //      one is the inverted-material drawing for a DARK taskbar.
  const lightTray = readPng(path.join(appDir, `tray-light-${TRAY_SOURCE}.png`))
  writePng(lightTray.width, lightTray.height, lightTray.rgba, path.join(ASSETS, 'icon.png'))
  console.log('Icon generated: assets/icon.png', `${lightTray.width}x${lightTray.height}`)

  const darkTray = readPng(path.join(appDir, `tray-dark-${TRAY_SOURCE}.png`))
  writePng(darkTray.width, darkTray.height, darkTray.rgba, path.join(ASSETS, 'icon-dark.png'))
  console.log('Icon generated: assets/icon-dark.png', `${darkTray.width}x${darkTray.height}`)

  // Sanity check: the two tray files must exist, be square, and be at least the
  // 24px the tray draws — a smaller source would be upscaled by the resize call.
  for (const name of ['icon.png', 'icon-dark.png']) {
    const img = readPng(path.join(ASSETS, name))
    if (img.width !== img.height) throw new Error(`${name} is not square`)
    if (img.width < TRAY_SIZES[0]) throw new Error(`${name} is smaller than the ${TRAY_SIZES[0]}px tray draws`)
    if (img.width !== TRAY_SOURCE) throw new Error(`${name} is not the expected ${TRAY_SOURCE}px source`)
  }
  console.log(`Tray sources ready (${TRAY_SOURCE}px, drawn at ${TRAY_SIZES.join('/')}px): assets/icon.png, assets/icon-dark.png`)
}

main()
