const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..')
const main = fs.readFileSync(path.join(root, 'main.js'), 'utf8')
const ocrIpc = fs.readFileSync(path.join(root, 'main/ipc/ocr-ipc.js'), 'utf8')
const aiIndex = fs.readFileSync(path.join(root, 'main/services/ai/index.js'), 'utf8')
// H05: the channel facade that calls the AI client lives in the aggregated IPC module.
const ipcIndex = fs.readFileSync(path.join(root, 'main/ipc/index.js'), 'utf8')

test('main process uses a single AI client entry instead of ad-hoc deepseek requires', () => {
  assert.match(main, /require\('\.\/main\/services\/ai'\)/)
  assert.match(main, /const aiClient = require\('\.\/main\/services\/ai'\)/)
  assert.doesNotMatch(main, /require\('\.\/deepseek'\)/)
  assert.match(main, /const aiClient = require\('\.\/main\/services\/ai'\)/)
  assert.match(ipcIndex, /aiClient\.validateApiKey/)
  assert.match(ipcIndex, /aiClient\.completeChat/)
  assert.match(ipcIndex, /aiClient\.translateText/)
  assert.match(ocrIpc, /aiClient\.translateOcrTextBlocks/)
  assert.match(aiIndex, /require\('\.\/client'\)/)
  assert.equal(fs.existsSync(path.join(root, 'main/services/ai/client.js')), true)
  const shim = fs.readFileSync(path.join(root, 'deepseek.js'), 'utf8')
  assert.match(shim, /require\('\.\/main\/services\/ai\/client'\)/)
})
